export function getDistrictsByDivision(division: string): DistrictInfo[] {
  return Object.values(BANGLADESH_DISTRICTS).filter(
    (d) => d.division.toLowerCase() === division.trim().toLowerCase()
  );
}

export function getUpazilas(districtName: string): string[] {
  const district = BANGLADESH_DISTRICTS[districtName] || Object.values(BANGLADESH_DISTRICTS).find(d => d.name.toLowerCase() === districtName.toLowerCase());
  return district ? district.upazilas : [];
}

export function getDistrictData(districtName: string): DistrictInfo | undefined {
  return BANGLADESH_DISTRICTS[districtName] || Object.values(BANGLADESH_DISTRICTS).find(d => d.name.toLowerCase() === districtName.toLowerCase());
}

